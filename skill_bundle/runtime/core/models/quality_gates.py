# -*- coding: utf-8 -*-
"""
Algorithm Quality Gates & Governance Engine (ALCM Phase 2).

Provides industrial-grade quantitative quality gates:
1. LookaheadGuard: AST static analysis & dynamic temporal perturbation probe
   to prevent future data leakage (Lookahead Bias).
2. AShareComplianceGuard: Validates A-share trading rules (T+1 settlement,
   limit-up/down non-fillable orders, suspension/zero-liquidity execution).
3. OverfittingGuard: Out-of-Sample (OOS) performance decay verification and
   Marcos López de Prado's Deflated Sharpe Ratio (DSR).
4. AlgorithmQualityGate: Composite evaluation gate orchestrator with
   structured pass/warning/block governance reporting.
"""
from __future__ import annotations

import ast
import inspect
import math
import statistics
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Callable, Dict, List, Optional, Tuple, Union

from core.config import get_logger

logger = get_logger("core.models.quality_gates")


class QualityGateStatus(str, Enum):
    """Quality gate decision status."""
    PASSED = "passed"      # Compliant with all hard gates & statistical baselines
    WARNING = "warning"    # Minor deviations or near-boundary metrics (advisory review)
    BLOCKED = "blocked"    # Hard gate violation (lookahead leakage, illegal trades, severe overfitting)


@dataclass
class QualityGateReport:
    """Structured compliance and validation report generated by Quality Gates."""
    target_name: str
    status: QualityGateStatus
    score: float                         # Composite governance score (0 - 100)
    passed_checks: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    violations: List[str] = field(default_factory=list)
    metrics: Dict[str, Any] = field(default_factory=dict)
    recommendations: List[str] = field(default_factory=list)

    def is_passed(self) -> bool:
        return self.status == QualityGateStatus.PASSED

    def to_dict(self) -> Dict[str, Any]:
        return {
            "target_name": self.target_name,
            "status": self.status.value,
            "score": round(self.score, 2),
            "passed_checks": list(self.passed_checks),
            "warnings": list(self.warnings),
            "violations": list(self.violations),
            "metrics": dict(self.metrics),
            "recommendations": list(self.recommendations),
        }


