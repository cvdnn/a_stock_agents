# G1.2: A股交易制度合规审查器 (AShareComplianceGuard)
# ==============================================================================
class AShareComplianceGuard:
    """
    A-Share Market Rule & Regulatory Compliance Guard.

    Validates:
    1. T+1 Settlement Rule: intraday buy-then-sell without prior overnight positions.
    2. Limit-up/Limit-down Matching: orders cannot fill on unyielding one-word limit boards.
    3. Trading Suspensions: zero volume / halted stock execution rejection.
    """

    @classmethod
    def audit_trade_log(
        cls,
        trades: List[Dict[str, Any]],
        klines_by_date: Optional[Dict[str, Dict[str, float]]] = None,
    ) -> Tuple[bool, List[str]]:
        """
        Audit a sequence of simulated trades against A-share rules.
        Returns: (is_compliant, violations)
        """
        violations = []
        if not trades:
            return True, []

        # 1. T+1 Rule validation
        positions: Dict[str, Dict[str, Any]] = {}
        # Track buy positions with timestamps/dates
        for trade in trades:
            code = trade.get("code", trade.get("symbol", "DEFAULT"))
            action = trade.get("action", "").lower()
            t_date = trade.get("date", "")
            qty = trade.get("qty", trade.get("shares", trade.get("volume", 0)))

            if code not in positions:
                positions[code] = {"available": 0, "frozen": 0, "last_buy_date": None}

            pos = positions[code]

            # Overnight rollover if date advanced
            if pos["last_buy_date"] and pos["last_buy_date"] != t_date:
                pos["available"] += pos["frozen"]
                pos["frozen"] = 0

            if action == "buy":
                pos["frozen"] += qty
                pos["last_buy_date"] = t_date
            elif action == "sell":
                if pos["available"] < qty:
                    # Illegal intraday sale without prior settled shares
                    violations.append(
                        f"T+1 Violation on {t_date} for {code}: attempted to sell {qty} shares, "
                        f"but only {pos['available']} were settled overnight (frozen intraday: {pos['frozen']})."
                    )
                else:
                    pos["available"] -= qty

            # 2. Limit price & Suspension checks if market context provided
            if klines_by_date and t_date in klines_by_date:
                k = klines_by_date[t_date]
                op = float(k.get("open", 0.0))
                cl = float(k.get("close", 0.0))
                hi = float(k.get("high", 0.0))
                lo = float(k.get("low", 0.0))
                vol = float(k.get("volume", 1.0))
                prev_cl = float(k.get("prev_close", cl))

                # Zero volume suspension
                if vol <= 0:
                    violations.append(f"Suspension execution violation on {t_date} for {code}: traded on 0 volume.")

                # One-word limit-up (open == high == low == close >= prev_close * 1.095)
                is_one_word_limit_up = (op == hi == lo == cl) and prev_cl > 0 and (cl >= prev_cl * 1.095)
                is_one_word_limit_down = (op == hi == lo == cl) and prev_cl > 0 and (cl <= prev_cl * 0.905)

                if action == "buy" and is_one_word_limit_up:
                    violations.append(f"Limit-up violation on {t_date} for {code}: bought on locked one-word limit-up.")
                if action == "sell" and is_one_word_limit_down:
                    violations.append(f"Limit-down violation on {t_date} for {code}: sold on locked one-word limit-down.")

        is_compliant = len(violations) == 0
        return is_compliant, violations


