# G2: 效能达标与过拟合门禁 (OverfittingGuard)
# ==============================================================================
class OverfittingGuard:
    """
    Overfitting, Statistical Significance & OOS Decay Guard.

    Implements:
    1. Out-of-Sample (OOS) performance decay verification.
    2. Marcos López de Prado's Deflated Sharpe Ratio (DSR) calibration.
    """

    @classmethod
    def calculate_oos_decay(
        cls,
        in_sample_metrics: Dict[str, Any],
        out_sample_metrics: Dict[str, Any],
        max_allowed_decay: float = 0.35,
    ) -> Tuple[bool, float, float, List[str]]:
        """
        Calculate performance retention and decay between In-Sample and Out-of-Sample.

        Returns:
            (is_acceptable, ret_decay_ratio, sharpe_decay_ratio, details)
        """
        is_ret = float(in_sample_metrics.get("annual_return_pct", in_sample_metrics.get("total_return_pct", 0.0)))
        oos_ret = float(out_sample_metrics.get("annual_return_pct", out_sample_metrics.get("total_return_pct", 0.0)))

        is_sr = float(in_sample_metrics.get("sharpe_ratio", 0.0))
        oos_sr = float(out_sample_metrics.get("sharpe_ratio", 0.0))

        details = []

        # Return decay: 1 - (oos / is)
        if is_ret > 0:
            ret_decay = 1.0 - (oos_ret / is_ret)
        else:
            ret_decay = 1.0 if oos_ret <= 0 else 0.0

        # Sharpe decay: 1 - (oos / is)
        if is_sr > 0:
            sr_decay = 1.0 - (oos_sr / is_sr)
        else:
            sr_decay = 1.0 if oos_sr <= 0 else 0.0

        details.append(f"In-Sample Return: {is_ret:.2f}%, OOS Return: {oos_ret:.2f}% (Decay: {ret_decay*100:.1f}%)")
        details.append(f"In-Sample Sharpe: {is_sr:.3f}, OOS Sharpe: {oos_sr:.3f} (Decay: {sr_decay*100:.1f}%)")

        is_acceptable = (sr_decay <= max_allowed_decay) and (oos_ret > 0)
        if not is_acceptable:
            details.append(
                f"OOS Sharpe decay ({sr_decay*100:.1f}%) exceeds safety threshold ({max_allowed_decay*100:.1f}%)"
            )

        return is_acceptable, ret_decay, sr_decay, details

    @classmethod
    def calculate_deflated_sharpe_ratio(
        cls,
        observed_sharpe: float,
        daily_returns: List[float],
        num_trials: int = 1,
        annualized: bool = True,
    ) -> Tuple[float, float, str]:
        """
        Calculate Deflated Sharpe Ratio (DSR) accounting for multiple testing,
        skewness, and fat tails (Marcos López de Prado, 2014).

        Returns:
            (dsr_probability, expected_max_sr, summary)
        """
        T = len(daily_returns)
        if T < 20:
            return 0.5, 0.0, "Sample size too small for statistical DSR calibration (requires T >= 20)"

        # Normalize daily returns
        mean_r = sum(daily_returns) / T
        var_r = sum((r - mean_r) ** 2 for r in daily_returns) / (T - 1)
        std_r = math.sqrt(var_r) if var_r > 0 else 1e-8

        # Skewness (gamma_3) & Kurtosis (gamma_4)
        skew = sum((r - mean_r) ** 3 for r in daily_returns) / (T * (std_r ** 3)) if std_r > 0 else 0.0
        kurt = sum((r - mean_r) ** 4 for r in daily_returns) / (T * (std_r ** 4)) if std_r > 0 else 3.0

        # Un-annualize Sharpe to sample frequency if observed was annualized
        sr = observed_sharpe / math.sqrt(250) if annualized else observed_sharpe

        # Expected maximum Sharpe under null hypothesis of N multiple trials
        gamma_euler = 0.5772156649015329
        n_trials = max(1, num_trials)
        if n_trials > 1:
            z_term = math.sqrt(2.0 * math.log(n_trials))
            expected_max_sr = (z_term - (math.log(math.pi) + math.log(math.log(n_trials))) / (2.0 * z_term)) / math.sqrt(250)
        else:
            expected_max_sr = 0.0

        # Asymptotic variance of Sharpe ratio: sigma_sr^2 = (1 - skew*sr + (kurt-1)/4 * sr^2) / (T - 1)
        var_sr = (1.0 - skew * sr + ((kurt - 1.0) / 4.0) * (sr ** 2)) / (T - 1)
        sigma_sr = math.sqrt(max(1e-9, var_sr))

        # Standardized Z-statistic
        z_stat = (sr - expected_max_sr) / sigma_sr

        # Normal CDF: Phi(Z)
        dsr_prob = 0.5 * (1.0 + math.erf(z_stat / math.sqrt(2.0)))

        summary = (
            f"DSR Confidence: {dsr_prob*100:.1f}% | Skewness: {skew:.2f}, Kurtosis: {kurt:.2f} | "
            f"Observed SR: {observed_sharpe:.2f}, Trials: {num_trials}"
        )
        return round(dsr_prob, 4), round(expected_max_sr * math.sqrt(250), 3), summary


