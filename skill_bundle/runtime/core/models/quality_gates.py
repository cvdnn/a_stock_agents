# G1.1: 无未来函数审查器 (LookaheadGuard)
# ==============================================================================
class LookaheadGuard:
    """
    Lookahead Bias & Future Leakage Guard.

    Combines:
    1. Static AST scan: detects forward slicing patterns (e.g., `i+1:`, `shift(-1)`).
    2. Dynamic Temporal Perturbation Probe: modifies future K-lines (t+1..T) and
       verifies whether the output at time `t` remains invariant.
    """

    @classmethod
    def audit_source_code(cls, func_or_class_or_code: Union[str, Any]) -> Tuple[bool, List[str]]:
        """
        Static AST code audit for obvious forward index lookaheads.
        Accepts function, class, or source code string.
        Returns: (is_clean, violations)
        """
        import textwrap
        violations = []

        if isinstance(func_or_class_or_code, str):
            source = textwrap.dedent(func_or_class_or_code)
        else:
            try:
                raw_src = inspect.getsource(func_or_class_or_code)
                source = textwrap.dedent(raw_src)
            except (TypeError, OSError):
                return True, ["Source code unavailable for dynamic introspection (built-in or C-extension)"]

        # Parse AST
        try:
            tree = ast.parse(source)
        except SyntaxError as e:
            return False, [f"AST parsing failed: {e}"]

        for node in ast.walk(tree):
            # Check for forward slice lower index like [idx + 1:] or [i+1]
            if isinstance(node, ast.Slice):
                if isinstance(node.lower, ast.BinOp) and isinstance(node.lower.op, ast.Add):
                    if isinstance(node.lower.right, ast.Constant) and isinstance(node.lower.right.value, (int, float)):
                        if node.lower.right.value > 0:
                            violations.append(
                                f"Suspicious forward slice offset detected: lower bound +{node.lower.right.value}"
                            )

            # Check for shift(-k)
            if isinstance(node, ast.Call):
                if isinstance(node.func, ast.Attribute) and node.func.attr == "shift":
                    for arg in node.args:
                        if isinstance(arg, ast.UnaryOp) and isinstance(arg.op, ast.USub):
                            violations.append("Pandas backward shift(-k) detected without forward alignment")

        is_clean = len(violations) == 0
        return is_clean, violations

    @classmethod
    def probe_temporal_integrity(
        cls,
        func: Callable[..., Any],
        sample_klines: List[Any],
        bar_index: Optional[int] = None,
        *args: Any,
        **kwargs: Any,
    ) -> Tuple[bool, str]:
        """
        Dynamic Temporal Perturbation Probe.

        Tests whether the output at target index `bar_index` changes when
        subsequent future data (idx+1..end) is heavily perturbed.
        """
        if not sample_klines or len(sample_klines) < 10:
            return True, "Insufficient sample K-lines for dynamic perturbation"

        t = bar_index if bar_index is not None else len(sample_klines) // 2
        t = max(2, min(t, len(sample_klines) - 2))

        # Deep copy original sequence
        import copy
        k_original = copy.deepcopy(sample_klines)
        k_perturbed = copy.deepcopy(sample_klines)

        # Apply extreme perturbation to all bars AFTER index t
        for i in range(t + 1, len(k_perturbed)):
            bar = k_perturbed[i]
            if isinstance(bar, list):
                # Format: [date, open, close, high, low, volume, ...]
                bar[1] = float(bar[1]) * 10.0
                bar[2] = float(bar[2]) * 10.0
                bar[3] = float(bar[3]) * 10.0
                bar[4] = float(bar[4]) * 10.0
                if len(bar) > 5:
                    bar[5] = float(bar[5]) * 100.0
            elif isinstance(bar, dict):
                bar["open"] = float(bar.get("open", 10.0)) * 10.0
                bar["close"] = float(bar.get("close", 10.0)) * 10.0
                bar["high"] = float(bar.get("high", 10.0)) * 10.0
                bar["low"] = float(bar.get("low", 10.0)) * 10.0
                bar["volume"] = float(bar.get("volume", 1000.0)) * 100.0

        # Execute on both original and perturbed sequence
        try:
            # Check if func accepts idx parameter
            sig = inspect.signature(func)
            if "idx" in sig.parameters:
                kwargs_t = dict(kwargs)
                kwargs_t["idx"] = t
                out_orig = func(k_original, *args, **kwargs_t)
                out_pert = func(k_perturbed, *args, **kwargs_t)
            else:
                # Sliced invocation up to t
                out_orig = func(k_original[: t + 1], *args, **kwargs)
                out_pert = func(k_perturbed[: t + 1], *args, **kwargs)

            # Compare outputs
            if out_orig != out_pert:
                return False, f"Output at bar {t} changed after future data perturbation (Lookahead Bias Detected!)"

            return True, f"Passed temporal perturbation probe at bar {t}"
        except Exception as exc:
            return False, f"Dynamic probe execution error: {exc}"


