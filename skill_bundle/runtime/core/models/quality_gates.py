# G_Total: 综合质量门禁中枢 (AlgorithmQualityGate)
# ==============================================================================
class AlgorithmQualityGate:
    """
    Master Quality Gate Controller.

    Orchestrates G1 (Research compliance, Lookahead & A-Share rules) and
    G2 (Performance threshold, OOS decay & Overfitting testing).
    """

    @classmethod
    def audit_algorithm(
        cls,
        name_or_func: Any,
        sample_klines: Optional[List[Any]] = None,
        trade_log: Optional[List[Dict[str, Any]]] = None,
        klines_by_date: Optional[Dict[str, Dict[str, float]]] = None,
        in_sample_metrics: Optional[Dict[str, Any]] = None,
        out_sample_metrics: Optional[Dict[str, Any]] = None,
        daily_returns: Optional[List[float]] = None,
        num_trials: int = 1,
    ) -> QualityGateReport:
        """
        Run the complete suite of quality gate checks on an algorithm.
        """
        algo_name = name_or_func if isinstance(name_or_func, str) else getattr(name_or_func, "__name__", str(name_or_func))
        passed_checks = []
        warnings = []
        violations = []
        metrics = {}
        recommendations = []
        score = 100.0

        # ── 1. G1: Lookahead Static Audit ──────────────────────────────────────
        if callable(name_or_func):
            is_clean, ast_violations = LookaheadGuard.audit_source_code(name_or_func)
            if is_clean:
                passed_checks.append("G1.1 AST static analysis: no forward slicing detected.")
            else:
                for v in ast_violations:
                    violations.append(f"G1.1 Code Audit: {v}")
                score -= 30.0

            # Dynamic probe
            if sample_klines and len(sample_klines) >= 10:
                is_probe_ok, probe_msg = LookaheadGuard.probe_temporal_integrity(name_or_func, sample_klines)
                if is_probe_ok:
                    passed_checks.append(f"G1.1 Temporal Probe: {probe_msg}")
                else:
                    violations.append(f"G1.1 Temporal Probe: {probe_msg}")
                    score -= 40.0

        # ── 2. G1: A-Share Rules Audit ─────────────────────────────────────────
        if trade_log:
            is_trade_ok, trade_violations = AShareComplianceGuard.audit_trade_log(trade_log, klines_by_date)
            if is_trade_ok:
                passed_checks.append(f"G1.2 A-share rules: all {len(trade_log)} trades adhere to T+1 & limit constraints.")
            else:
                for tv in trade_violations:
                    violations.append(f"G1.2 Market Rules: {tv}")
                score -= min(40.0, len(trade_violations) * 15.0)

        # ── 3. G2: Performance & OOS Decay ─────────────────────────────────────
        if in_sample_metrics and out_sample_metrics:
            is_oos_ok, ret_decay, sr_decay, oos_details = OverfittingGuard.calculate_oos_decay(
                in_sample_metrics, out_sample_metrics
            )
            metrics["oos_ret_decay_pct"] = round(ret_decay * 100, 2)
            metrics["oos_sharpe_decay_pct"] = round(sr_decay * 100, 2)

            if is_oos_ok:
                passed_checks.append(f"G2.1 OOS Validation: Sharpe decay {sr_decay*100:.1f}% within 35% tolerance.")
            else:
                warnings.append(f"G2.1 OOS Validation: Sharpe decay {sr_decay*100:.1f}% exceeds tolerance.")
                recommendations.append("Reduce parameter degrees of freedom or introduce L2/volatility regularization.")
                score -= 20.0

        # ── 4. G2: Deflated Sharpe Ratio (DSR) ──────────────────────────────────
        if daily_returns and in_sample_metrics:
            obs_sr = float(in_sample_metrics.get("sharpe_ratio", 1.0))
            dsr_prob, exp_max_sr, dsr_summary = OverfittingGuard.calculate_deflated_sharpe_ratio(
                observed_sharpe=obs_sr,
                daily_returns=daily_returns,
                num_trials=num_trials,
            )
            metrics["dsr_confidence_pct"] = round(dsr_prob * 100, 2)
            metrics["expected_max_trial_sr"] = exp_max_sr

            if dsr_prob >= 0.80:
                passed_checks.append(f"G2.2 DSR Audit: {dsr_summary} (High Statistical Significance)")
            elif dsr_prob >= 0.50:
                warnings.append(f"G2.2 DSR Audit: Moderate confidence ({dsr_prob*100:.1f}%). May have trial selection bias.")
                score -= 10.0
            else:
                violations.append(f"G2.2 DSR Audit: Low confidence ({dsr_prob*100:.1f}%). High probability of overfitted false discovery.")
                recommendations.append("Increase out-of-sample test sample duration or decrease parameter search grids.")
                score -= 25.0

        # Score lower bound
        score = max(0.0, score)

        # Decision status
        if violations:
            status = QualityGateStatus.BLOCKED
        elif warnings or score < 80.0:
            status = QualityGateStatus.WARNING
        else:
            status = QualityGateStatus.PASSED

        return QualityGateReport(
            target_name=algo_name,
            status=status,
            score=score,
            passed_checks=passed_checks,
            warnings=warnings,
            violations=violations,
            metrics=metrics,
            recommendations=recommendations,
        )
